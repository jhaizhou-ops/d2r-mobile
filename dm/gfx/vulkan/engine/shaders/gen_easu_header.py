"""Compile easu_upsample.frag (two variants) with glslc and write ../xbg_easu_spv.h.
Usage: python gen_easu_header.py <glslc>   (the NDK's shader-tools glslc works)"""
import os, subprocess, sys, tempfile
here = os.path.dirname(os.path.abspath(__file__)); glslc = sys.argv[1]
out = ['// Generated by shaders/gen_easu_header.py from shaders/easu_upsample.frag; do not edit.', '#pragma once', '#include <stdint.h>']
for name, defs in (('xbg_easu_rcas_spv', []), ('xbg_easu_only_spv', ['-DRCAS=0'])):
    with tempfile.TemporaryDirectory() as t:
        spv = os.path.join(t, 'o.spv')
        subprocess.run([glslc, '--target-env=vulkan1.1', '-O', *defs, '-o', spv, os.path.join(here, 'easu_upsample.frag')], check=True)
        b = open(spv, 'rb').read()
    w = [int.from_bytes(b[i:i + 4], 'little') for i in range(0, len(b), 4)]
    out.append('static const uint32_t %s[%d] = {' % (name, len(w)))
    out += ['    ' + ','.join('0x%08x' % x for x in w[i:i + 8]) + ',' for i in range(0, len(w), 8)]
    out.append('};')
open(os.path.join(here, '..', 'xbg_easu_spv.h'), 'w', newline='\n').write('\n'.join(out) + '\n')
