#!/usr/bin/env python3
"""生成 romfs_samples.h：资源自检探针（game_resource_probe.c）的期望值。
数据来源 = 玩家自己的 RomFS（游戏文件，仓库不带）。用法：
    python3 dm/android/tools/gen_romfs_samples.py [RomFS 目录] [输出头文件]
缺省 RomFS = $DM_ROMFS 或 $DM_ROOT/data/switch/3.3.94012/Update/RomFS（再缺省 ~/dm-work/...）。
生成内容与探针结构一一对应：
  · resource_samples：3 条样本（.build.config / 00-00000001.data / 00-00000002.data）各取前 256 字节；
  · resource_entries：data 目录下全部文件（.build.config + 45 个 *.data）的 {名, 尺寸}。
Generates the expectation header for the resource probe; source is the user's own RomFS."""
import os
import sys

SAMPLE_FILES = (".build.config", "00-00000001.data", "00-00000002.data")
BYTES = 256


def find_romfs() -> str:
    if len(sys.argv) > 1:
        return sys.argv[1]
    env = os.environ.get("DM_ROMFS")
    if env:
        return env
    root = os.environ.get("DM_ROOT", os.path.expanduser("~/dm-work"))
    return os.path.join(root, "data/switch/3.3.94012/Update/RomFS")


def main() -> int:
    romfs = find_romfs()
    data = os.path.join(romfs, "data")
    if not os.path.isdir(data):
        sys.stderr.write(f"romfs_samples：找不到 {data}（把玩家 RomFS 放到位或传参）\n")
        return 2
    out_path = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(__file__), "..", "build", "generated", "romfs_samples.h")
    out_path = os.path.abspath(out_path)
    os.makedirs(os.path.dirname(out_path), exist_ok=True)

    lines = ["/* generated by dm/android/tools/gen_romfs_samples.py from the user's own RomFS */\n",
             "static const struct resource_sample resource_samples[] = {\n"]
    for name in SAMPLE_FILES:
        path = os.path.join(data, name)
        with open(path, "rb") as f:
            blob = f.read(BYTES)
        if len(blob) != BYTES:
            sys.stderr.write(f"romfs_samples：{path} 不足 {BYTES} 字节\n")
            return 2
        size = os.path.getsize(path)
        bytes_list = ",".join(f"0x{b:02x}" for b in blob)
        lines.append(f'    {{"/data/{name}", {size}LL, {{{bytes_list}}}}},\n')
    lines.append("};\n")
    lines.append("static const struct resource_entry resource_entries[] = {\n")
    for name in sorted(os.listdir(data)):
        path = os.path.join(data, name)
        if not os.path.isfile(path):
            continue
        lines.append(f'    {{"{name}", {os.path.getsize(path)}LL}},\n')
    lines.append("};\n")
    with open(out_path, "w") as f:
        f.writelines(lines)
    sys.stdout.write(f"romfs_samples：{out_path}（样本 {len(SAMPLE_FILES)} 条 × {BYTES} 字节）\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
