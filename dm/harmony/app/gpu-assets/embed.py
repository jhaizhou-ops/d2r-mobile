"""Embed audited fixed bytes; no resource generation or shader substitution."""
import hashlib
import json
import struct
from pathlib import Path

root = Path(__file__).resolve().parent
names = ['q_val0', 'q_val8', 'q_dlt0', 'q_dlt8']
shader_hashes = [
    'f7e436a92a9eae931d04875a1b422b7c2a7225d0db3dca56c31dd910263e89e7',
    'bef5d75136c86b2ecc04ea326e8c4d7ab69caccae86a93258ce8839133a1cd34',
    'c72fb0ce7555755677bc20b5f2f46eaa5571ce2f5c7c2011111e6d632758c2be',
    'd9d570befe59c6e00edbabf9dba9e19389a8ec0129b15f5dae591c13d4110952',
]
manifest = json.loads((root / 'fixtures/fixture-manifest.json').read_text(encoding='utf-8-sig'))
files = [(root / 'kernels' / (n + '.spv'), n + '_spv', h) for n, h in zip(names, shader_hashes)]
files += [(root / 'fixtures' / e['filename'], e['filename'].replace('.', '_').replace('-', '_'), e['sha256']) for e in manifest['files']]
for n in ['sample.vert', 'sample.frag']:
    path = root / (n + '.spv')
    if path.exists():
        files.append((path, n.replace('.', '_') + '_spv', hashlib.sha256(path.read_bytes()).hexdigest()))
out = ['// Generated by gpu-assets/embed.py from hash-checked probe assets.', '#pragma once', '#include <cstdint>', 'namespace gpu_assets {']
for path, symbol, expected in files:
    data = path.read_bytes()
    assert hashlib.sha256(data).hexdigest() == expected, path
    assert len(data) % 4 == 0, path
    words = struct.unpack('<' + 'I' * (len(data) // 4), data)
    out.append(f'inline constexpr uint32_t {symbol}[] = {{')
    out.extend('    ' + ', '.join(f'0x{x:08x}u' for x in words[i:i+8]) + ',' for i in range(0,len(words),8))
    out.append('};')
    out.append(f'inline constexpr const char *{symbol}_sha256 = "{expected}";')
out.append('}')
(root.parent / 'entry/src/main/cpp/gpu_assets.h').write_text('\n'.join(out)+'\n',encoding='utf-8')
print(f'Embedded {len(files)} checked inputs')
