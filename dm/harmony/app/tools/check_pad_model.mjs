import assert from 'node:assert/strict';
import { PadModel } from '../entry/src/main/ets/input/PadModel.ts';

const pad = new PadModel();
const zero = { buttons: 0, lx: 0, ly: 0 };
pad.down(1, 82, 120);
assert.deepEqual(pad.frame(), zero);
pad.move(1, 86, 120);
assert.deepEqual(pad.frame(), zero, 'dead zone');
pad.move(1, 130, 120);
assert.deepEqual(pad.frame(), { buttons: 0, lx: 32767, ly: 0 });
pad.down(2, 372, 120);
assert.deepEqual(pad.frame(), { buttons: 1, lx: 32767, ly: 0 }, 'move and A simultaneously');
pad.down(3, 324, 72);
assert.equal(pad.frame().buttons, 5, 'two simultaneous action buttons');
pad.up(2);
assert.equal(pad.frame().buttons, 4, 'release only its own finger');
pad.move(3, 200, 120);
assert.equal(pad.frame().buttons, 0, 'slide out releases button');
pad.move(1, 800, -500);
assert.ok(Math.abs(Math.hypot(pad.frame().lx, pad.frame().ly) - 32767) < 1, 'radial clamp');
assert.ok(pad.frame().ly > 0, 'up is positive');
pad.up(1);
assert.deepEqual(pad.frame(), zero, 'stick returns to center');
pad.reset();
pad.down(4, 200, 120);
pad.move(4, 130, 120);
assert.deepEqual(pad.frame(), zero, 'blank touch cannot become movement');
pad.down(5, 82, 120);
pad.down(6, 82, 120);
pad.move(6, 130, 120);
assert.deepEqual(pad.frame(), zero, 'second finger cannot steal stick');
pad.move(5, 82, 72);
assert.deepEqual(pad.frame(), { buttons: 0, lx: 0, ly: 32767 });
pad.reset();
assert.deepEqual(pad.frame(), zero, 'cancel/background clear all');
pad.down(7, 372, 120);
pad.down(8, 372, 120);
pad.up(7);
assert.equal(pad.frame().buttons, 1, 'one of two fingers still holds button');
pad.up(8);
assert.deepEqual(pad.frame(), zero);
console.log('PASS: production PadModel movement, dead zone, clamp, multi-touch, slide-out, release and reset. UI dispatch and game consumption not tested.');
